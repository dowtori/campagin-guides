local H=require('./ClientHarness')
local Engine=require('./TrainingEngine')
local Curriculum=require('./Curriculum')
local Main=require('./ClientMain')
local n=0
local function expect(value,message)n+=1 assert(value,message)end
Main.start()
expect(H.playerGui:FindFirstChild('SiriaiTraining')~=nil,'startup creates real HUD')
expect(H.find('첫 미션으로 이동')~=nil,'welcome dialog renders')
H.find('첫 미션으로 이동').Activated:Fire()
expect(H.packets[#H.packets].kind=='jump' and H.packets[#H.packets].stage==1,'welcome action reaches server')
H.remote.OnClientEvent:Fire({kind='close'})
expect(H.prompts.Enabled,'closing restores prompts')
H.root.Position={X=-58,Y=4,Z=10};H.run.Heartbeat:Fire(.3)
local start=H.find('미션 시작 [E]');expect(start.Visible,'inside booth offers visible mission entry')
start.Activated:Fire()
expect(H.packets[#H.packets].kind=='open' and H.packets[#H.packets].stage==1,'on-screen entry reaches same stage')
H.input.InputBegan:Fire({KeyCode=H.Enum.KeyCode.E},false)
expect(H.packets[#H.packets].kind=='open','E backup entry works')
local state=Engine.new();Engine.open(state,Curriculum,1)
H.remote.OnClientEvent:Fire({kind='question',question=Engine.question(state,Curriculum),token='token'})
expect(not H.warning,'actual question renders without startup/event error')
expect(not start.Visible,'mission entry does not overlay modal')
expect(H.find('VisualChoice_a')~=nil,'full client connects to visual task')
H.remote.OnClientEvent:Fire({kind='close'})
H.remote.OnClientEvent:Fire({kind='relax'})
expect(H.find('교육으로 돌아가기').Text:find('교육으로 돌아가기')~=nil,'rest can return')
H.find('교육으로 돌아가기').Activated:Fire();expect(H.packets[#H.packets].kind=='return','return sends server packet')
H.remote.OnClientEvent:Fire({kind='close'})
expect(#H.all()>400,'approved real logo pixels are instantiated even without editable-image API')
print(string.format('PASS: %d full client startup/event checks: welcome, HUD, native image fallback, booth button, E, task modal, rest/return',n))

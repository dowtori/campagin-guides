"""Run pure Luau gameplay tests plus structural checks of the actual exported place.
Usage: python tests/run_tests.py --luau PATH_TO_LUAU_EXE
"""
import argparse, json, shutil, subprocess, tempfile, xml.etree.ElementTree as ET, math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def lua(value):
    if value is None: return 'nil'
    if isinstance(value,bool): return 'true' if value else 'false'
    if isinstance(value,(int,float)): return repr(value)
    if isinstance(value,str): return json.dumps(value,ensure_ascii=False)
    if isinstance(value,list): return '{'+','.join(lua(v) for v in value)+'}'
    return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in value.items())+'}'
parser=argparse.ArgumentParser();parser.add_argument('--luau',required=True);args=parser.parse_args()
place=ROOT/'downloads/SIRIAI_Training_Campus.rbxlx'
xml=ET.parse(place).getroot();items=list(xml.iter('Item'))
classes={}
for item in items: classes[item.attrib['class']]=classes.get(item.attrib['class'],0)+1
assert classes.get('SpawnLocation')==1
assert classes.get('ProximityPrompt')==6
assert classes.get('RemoteEvent')==1
assert classes.get('Script')==1 and classes.get('LocalScript')==1
assert classes.get('ModuleScript')==2
for item in items:
    if item.attrib['class']=='Part':
        assert item.find("Properties/bool[@name='Anchored']").text=='true'
for stage_id in range(1,7):
    assert any(it.find("Properties/string[@name='Name']") is not None and it.find("Properties/string[@name='Name']").text==f'Station{stage_id:02d}' for it in items)
source='\n'.join(el.text or '' for el in xml.findall('.//Properties/*[@name=\"Source\"]'))
for forbidden in ['rbxassetid://','InsertService','loadstring(','GetAsync(','PostAsync(','DataStoreService']:
    assert forbidden not in source,forbidden
# The actual ModuleScript generated by Rojo is tested, not a second curriculum copy.
modules={}
for it in items:
    if it.attrib['class']=='ModuleScript':
        name=it.find("Properties/string[@name='Name']").text
        modules[name]=it.find("Properties/*[@name='Source']").text
with tempfile.TemporaryDirectory(prefix='siriai-roblox-tests-', dir=ROOT/'tests') as directory:
    tmp=Path(directory)
    assert tmp.resolve().is_relative_to((ROOT/'tests').resolve())
    for name,value in modules.items(): (tmp/(name+'.lua')).write_text(value,encoding='utf-8')
    shutil.copyfile(ROOT/'tests/engine.spec.lua',tmp/'engine.spec.lua')
    subprocess.run([str(Path(args.luau).resolve()),str(tmp/'engine.spec.lua')],check=True,cwd=tmp)
print('PASS: exported place structure / 536 original parts / 6 prompts / no external asset IDs or network calls')
print('Roblox Studio runtime and account publishing have not been tested here.')

"""Run pure Luau gameplay tests plus structural checks of the actual exported place.
Usage: python tests/run_tests.py --luau PATH_TO_LUAU_EXE
"""
import argparse, json, shutil, subprocess, tempfile, xml.etree.ElementTree as ET, math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def lua(value):
    if value is None: return 'nil'
    if isinstance(value,bool): return 'true' if value else 'false'
    if isinstance(value,(int,float)): return repr(value)
    if isinstance(value,str): return json.dumps(value,ensure_ascii=False)
    if isinstance(value,list): return '{'+','.join(lua(v) for v in value)+'}'
    return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in value.items())+'}'
parser=argparse.ArgumentParser();parser.add_argument('--luau',required=True);args=parser.parse_args()
place=ROOT/'downloads/SIRIAI_Training_Campus.rbxlx'
xml=ET.parse(place).getroot();items=list(xml.iter('Item'))
classes={}
for item in items: classes[item.attrib['class']]=classes.get(item.attrib['class'],0)+1
assert classes.get('SpawnLocation')==1
assert classes.get('ProximityPrompt')==6
assert classes.get('RemoteEvent')==1
assert classes.get('Script')==2 and classes.get('LocalScript')==3
assert classes.get('ModuleScript')==21
for item in items:
    if item.attrib['class']=='Part':
        assert item.find("Properties/bool[@name='Anchored']").text=='true'
for stage_id in range(1,7):
    assert any(it.find("Properties/string[@name='Name']") is not None and it.find("Properties/string[@name='Name']").text==f'Station{stage_id:02d}' for it in items)
source='\n'.join(el.text or '' for el in xml.findall('.//Properties/*[@name=\"Source\"]'))
for forbidden in ['loadstring(','DataStoreService']:
    assert forbidden not in source,forbidden
# The actual ModuleScript generated by Rojo is tested, not a second curriculum copy.
modules={}
for it in items:
    if it.attrib['class']=='ModuleScript':
        name=it.find("Properties/string[@name='Name']").text
        modules[name]=it.find("Properties/*[@name='Source']").text
with tempfile.TemporaryDirectory(prefix='siriai-roblox-tests-', dir=ROOT/'tests') as directory:
    tmp=Path(directory)
    assert tmp.resolve().is_relative_to((ROOT/'tests').resolve())
    for name,value in modules.items(): (tmp/(name+'.lua')).write_text(value,encoding='utf-8')
    rasterIndexPrefix="local script={Parent={WaitForChild=function()return {WaitForChild=function(_,key)return './'..key end}end}}\n"
    (tmp/'RasterAssets.lua').write_text(rasterIndexPrefix+modules['RasterAssets'],encoding='utf-8')
    shutil.copyfile(ROOT/'tests/engine.spec.lua',tmp/'engine.spec.lua')
    shutil.copyfile(ROOT/'tests/NativeUiMock.lua',tmp/'NativeUiMock.lua')
    shutil.copyfile(ROOT/'tests/visual-ui.spec.lua',tmp/'visual-ui.spec.lua')
    visual=modules['VisualTutorials'].replace("require(script.Parent:WaitForChild('VisualAssets'))","require('./VisualAssets')").replace("require(script.Parent:WaitForChild('RasterRenderer'))","require('./RasterRenderer')")
    prefix="local Mock=require('./NativeUiMock')\nlocal Instance,Color3,UDim,UDim2,Enum,game=Mock.Instance,Mock.Color3,Mock.UDim,Mock.UDim2,Mock.Enum,Mock.game\n"
    (tmp/'VisualTutorials.lua').write_text(prefix+visual,encoding='utf-8')
    raster=modules['RasterRenderer'].replace("require(script.Parent:WaitForChild('RasterAssets'))","require('./RasterAssets')")
    rasterPrefix="local Mock=require('./NativeUiMock')\nlocal Instance,Color3,UDim,UDim2,Enum,game=Mock.Instance,Mock.Color3,Mock.UDim,Mock.UDim2,Mock.Enum,Mock.game\nlocal Vector2={new=function(x,y)return {X=x,Y=y}end,zero={X=0,Y=0}}\n"
    (tmp/'RasterRenderer.lua').write_text(rasterPrefix+raster,encoding='utf-8')
    client=modules['ClientMain'].replace("require(script.Parent:WaitForChild('VisualTutorials'))","require('./VisualTutorials')").replace("require(script.Parent:WaitForChild('RasterRenderer'))","require('./RasterRenderer')")
    clientPrefix="local H=require('./ClientHarness')\nlocal game,workspace,Instance,Color3,UDim,UDim2,Vector2,Vector3,Enum,task,TweenInfo,warn=H.game,H.workspace,H.Instance,H.Color3,H.UDim,H.UDim2,H.Vector2,H.Vector3,H.Enum,H.task,H.TweenInfo,H.warn\n"
    (tmp/'ClientMain.lua').write_text(clientPrefix+client,encoding='utf-8')
    for name in ['ServerHarness.lua','relax.spec.lua','ClientHarness.lua','client-startup.spec.lua','booth-entry.spec.lua']:
        shutil.copyfile(ROOT/'tests'/name,tmp/name)
    server=next(it.find("Properties/*[@name='Source']").text for it in items if it.attrib['class']=='Script' and it.find("Properties/string[@name='Name']").text=='TrainingServer')
    header="local H=require('./ServerHarness')\nlocal game,workspace,Instance,Vector3,CFrame,task,os=H.game,H.workspace,H.Instance,H.Vector3,H.CFrame,H.task,H.os\nlocal script={Parent={WaitForChild=function(_,name)return './'..name end}}\n"
    (tmp/'TrainingServer.lua').write_text(header+server+'\nreturn true',encoding='utf-8')
    for test in ['engine.spec.lua','visual-ui.spec.lua','relax.spec.lua','client-startup.spec.lua','booth-entry.spec.lua']:
        subprocess.run([str(Path(args.luau).resolve()),str(tmp/test)],check=True,cwd=tmp)
print(f"PASS: exported place structure / {classes.get('Part',0)+classes.get('SpawnLocation',0)} original parts / 6 prompts / embedded approved/generated image assets")
print('Roblox Studio runtime and account publishing have not been tested here.')
